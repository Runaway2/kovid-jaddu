#!/usr/bin/env node
// Regenerates the project cards in index.html from projects.json.
// Usage: node build.js

const fs = require("fs");
const path = require("path");

const ROOT = __dirname;
const HTML_PATH = path.join(ROOT, "index.html");
const DATA_PATH = path.join(ROOT, "projects.json");

const START = "<!-- PROJECTS:START — generated by build.js from projects.json. Do not hand-edit between these markers. -->";
const END = "<!-- PROJECTS:END -->";

function escapeHtml(str) {
  return String(str)
    .replace(/&(?!amp;|lt;|gt;|#39;|quot;)/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;");
}

function cardHtml(project, index) {
  const colorClass = project.colorClass || `c-${(index % 8) + 1}`;
  const classes = ["card", project.wide ? "wide" : "", colorClass].filter(Boolean).join(" ");
  const stack = (project.stack || []).map((s) => escapeHtml(s).toUpperCase()).join(" · ");
  const invariant = project.invariant
    ? `\n        <div class="invariant">${project.invariant}</div>`
    : "";

  return `      <div class="${classes}">
        <div class="stack">${stack}</div>
        <h3>${escapeHtml(project.title)}</h3>
        <p>${project.description}</p>${invariant}
        <a class="pill-link" href="${project.linkUrl}" target="_blank" rel="noopener">${escapeHtml(project.linkLabel)} <span>&rsaquo;</span></a>
      </div>`;
}

function main() {
  const projects = JSON.parse(fs.readFileSync(DATA_PATH, "utf8"));
  const html = fs.readFileSync(HTML_PATH, "utf8");

  const startIdx = html.indexOf(START);
  const endIdx = html.indexOf(END);
  if (startIdx === -1 || endIdx === -1) {
    console.error("Could not find PROJECTS:START / PROJECTS:END markers in index.html");
    process.exit(1);
  }

  const cardsHtml = projects.map(cardHtml).join("\n\n");
  const before = html.slice(0, startIdx + START.length);
  const after = html.slice(endIdx);
  const updated = `${before}\n${cardsHtml}\n      ${after}`;

  fs.writeFileSync(HTML_PATH, updated);
  console.log(`Rebuilt index.html with ${projects.length} project card(s).`);
}

main();
